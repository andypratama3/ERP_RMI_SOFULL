if ($pdo instanceof PDO) {
    // Active users with missing dept/office
    if (ra_table_exists($pdo, 'master_system_login')) {
        try {
            $sql = "SELECT COUNT(*) FROM master_system_login
                    WHERE UPPER(COALESCE(status,''))='ACTIVE'
                      AND (COALESCE(TRIM(department),'')='' OR COALESCE(TRIM(office_code),'')='')";
            $cnt = (int)$pdo->query($sql)->fetchColumn();
            ra_add_check(
                $checks,
                'ACCOUNT READINESS',
                'Active users missing dept/office',
                $cnt === 0 ? 'PASS' : 'WARN',
                $cnt === 0 ? 'Tidak ada akun bermasalah.' : ("Ditemukan {$cnt} akun aktif tanpa department/office."),
                'master_system_login'
            );
        } catch (Throwable $e) {
            ra_add_check($checks, 'ACCOUNT READINESS', 'Active users missing dept/office', 'WARN', 'Query gagal dieksekusi.', 'master_system_login');
        }
    } else {
        ra_add_check($checks, 'ACCOUNT READINESS', 'master_system_login table ready', 'WARN', 'Table tidak ditemukan di DB aktif.', 'master_system_login');
    }

