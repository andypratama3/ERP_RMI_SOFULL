if (!function_exists('ra_h')) {
    function ra_h(string $s): string
    {
        return htmlspecialchars($s, ENT_QUOTES, 'UTF-8');
    }
}

if (!function_exists('ra_root')) {
    function ra_root(): string
    {
        return defined('RMI_ROOT') ? (string)RMI_ROOT : (realpath(__DIR__ . '/..') ?: dirname(__DIR__));
    }
}

if (!function_exists('ra_storage')) {
    function ra_storage(string $name): string
    {
        return ra_root() . '/storage/audit/' . ltrim($name, '/');
    }
}

if (!function_exists('ra_add_check')) {
    /**
     * @param array<int,array<string,mixed>> $rows
     */
    function ra_add_check(array &$rows, string $domain, string $name, string $status, string $detail, string $evidence): void
    {
        $rows[] = [
            'domain' => $domain,
            'name' => $name,
            'status' => strtoupper($status),
            'detail' => $detail,
            'evidence' => $evidence,
        ];
    }
}

if (!function_exists('ra_table_exists')) {
    function ra_table_exists(PDO $pdo, string $table): bool
    {
        try {
            $pdo->query("SELECT 1 FROM " . $table . " LIMIT 1");
            return true;
        } catch (Throwable $e) {
            return false;
        }
    }
}

if (!function_exists('ra_file_contains')) {
    function ra_file_contains(string $path, string $needle): bool
    {
        if (!is_file($path)) return false;
        $raw = (string)@file_get_contents($path);
        return $raw !== '' && str_contains($raw, $needle);
    }
}

if (!function_exists('ra_to_markdown')) {
    /**
     * @param array<int,array<string,mixed>> $rows
     */
    function ra_to_markdown(array $rows, string $by, string $generatedAt, string $gate): string
    {
        $md = "# Readiness Audit Report (Auto)\n\n";
        $md .= "- Generated at: `{$generatedAt}`\n";
        $md .= "- Generated by: `{$by}`\n";
        $md .= "- Gate result: **{$gate}**\n\n";
        $md .= "| Domain | Check | Status | Detail | Evidence |\n";
        $md .= "|---|---|---|---|---|\n";
        foreach ($rows as $r) {
            $domain = str_replace('|', '\\|', (string)($r['domain'] ?? ''));
            $name = str_replace('|', '\\|', (string)($r['name'] ?? ''));
            $status = strtoupper((string)($r['status'] ?? 'WARN'));
            $detail = str_replace('|', '\\|', (string)($r['detail'] ?? ''));
            $evidence = str_replace('|', '\\|', (string)($r['evidence'] ?? ''));
            $md .= "| {$domain} | {$name} | {$status} | {$detail} | `{$evidence}` |\n";
        }
        return $md . "\n";
    }
}

