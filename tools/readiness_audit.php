    if (ra_table_exists($pdo, 'auth_mfa_bypass_tickets')) {
        try {
            $sql = "SELECT COUNT(*) FROM auth_mfa_bypass_tickets
                    WHERE is_active=1
                      AND UPPER(COALESCE(status,''))='APPROVED'
                      AND expires_at IS NOT NULL
                      AND expires_at < NOW()";
            $cnt = (int)$pdo->query($sql)->fetchColumn();
            ra_add_check(
                $checks,
                'SECURITY',
                'Expired MFA bypass still active',
                $cnt === 0 ? 'PASS' : 'WARN',
                $cnt === 0 ? 'Tidak ada bypass kedaluwarsa yang aktif.' : ("Ditemukan {$cnt} bypass aktif yang sudah kedaluwarsa."),
